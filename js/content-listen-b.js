// 会話の聞き取り(listen):場面5〜8 機械・IT・総務・整備
(() => {
  const { pick, rint, comma, man, yen, dec } = DN.U;
  DN.C.scenarios = DN.C.scenarios || [];

  // ---- 5. 会議:破砕機の更新 ----
  DN.C.scenarios.push(lv => {
    const y = rint(12, 18), r = pick([180, 240, 320]), dt = rint(3, 8);
    const [N, s] = pick([[2400, 20], [2400, 25], [3000, 25], [3600, 30], [3600, 20]]), months = N / s;
    const L = [
      ['A', '破砕機の件、状況を教えてください。'],
      ['B', `導入から${y}年たちました。去年の修理費は${r}万円です。`],
    ];
    if (lv >= 2) L.push(['B', `先月は、故障で${dt}日止まりました。`]);
    L.push(['B', `新しい機械の見積もりは、${man(N)}です。`]);
    if (lv >= 2) L.push(['B', `電気代と修理費で、月に${s}万円ほど下がる見込みです。`]);
    L.push(['A', '来月の役員会で判断しましょう。資料をお願いします。']);
    const qa = [['破砕機は、導入から何年?', `${y}年`], ['新しい機械の見積もりは?', man(N)]];
    if (lv >= 2) qa.push(['先月、故障で何日止まった?', `${dt}日`], ['月にいくら下がる見込み?', `${s}万円`]);
    if (lv >= 3) qa.push(['削減額だけで考えると、何年で元が取れる?', `${months}か月、約${dec(months / 12, 1)}年`, 12]);
    return { topic: '会議 · 設備の更新', intro: '会議の聞き取りです。工場長と設備担当が、破砕機の更新について話しています。', points: '年数、金額、次にやること', names: { A: '工場長', B: '設備担当' }, lines: L, qa,
      summary: `導入${y}年の破砕機は、去年の修理費が${r}万円。新しい機械は${man(N)}${lv >= 2 ? `で、月${s}万円下がる見込み` : ''}。来月の役員会で判断する。` };
  });

  // ---- 6. 電話:配車システムの案内 ----
  DN.C.scenarios.push(lv => {
    const p = pick([3000, 4000, 5000]), n = pick([10, 12, 15, 20]), init = pick([20, 30, 50]), trial = pick([14, 30]);
    const L = [
      ['B', 'お世話になります。配車システムのご案内で、お電話しました。'],
      ['A', 'はい。どういう仕組みですか。'],
      ['B', '車両ごとの位置と、回収の進み具合が、スマホで見られます。'],
      ['A', '料金はどうなっていますか。'],
      ['B', `車両1台あたり、月${comma(p)}円です。`],
    ];
    if (lv >= 2) L.push(['B', `ほかに、初期費用が${init}万円かかります。`]);
    L.push(['A', `うちは収集車が${n}台あります。`]);
    if (lv >= 2) L.push(['B', `まずは${trial}日間、無料でお試しいただけます。`]);
    if (lv >= 3) L.push(['B', '年払いにしていただくと、2か月分が無料になります。']);
    L.push(['A', '資料をメールで送ってください。検討します。']);
    const qa = [['1台あたりの月額は?', `${comma(p)}円`], ['自社の収集車は何台?', `${n}台`]];
    if (lv >= 2) qa.push(['月額の合計はいくら?', yen(p * n), 8], ['初期費用と、無料お試しの日数は?', `初期費用${init}万円、お試し${trial}日`]);
    if (lv >= 3) qa.push(['年払いにすると、1年分はいくら?', `10か月分で${yen(p * n * 10)}`, 12]);
    return { topic: '電話 · システムの案内', intro: '電話の聞き取りです。システム会社から、配車システムの案内です。', points: '料金と条件', names: { A: '自社', B: 'システム会社' }, lines: L, qa,
      summary: `配車システムは1台月${comma(p)}円で、${n}台なら月${yen(p * n)}。${lv >= 2 ? `初期費用${init}万円、${trial}日の無料お試しあり。` : ''}資料をもらって検討する。` };
  });

  // ---- 7. 会議:総務の月次報告 ----
  DN.C.scenarios.push(lv => {
    const [staff, ot] = pick([[40, 600], [50, 600], [60, 600], [50, 750], [60, 900], [50, 900], [40, 800]]);
    const now = pick([45, 52, 58]), quit = rint(2, 4), plan = quit + rint(1, 3);
    const dept = pick(['収集運搬部', '中間処理の工場']);
    const L = [
      ['A', '総務から、今月の報告をお願いします。'],
      ['B', `社員${staff}人で、残業は合計${ot}時間でした。`],
    ];
    if (lv >= 2) L.push(['B', `有給の取得率は${now}%です。目標は70%です。`]);
    if (lv >= 3) L.push(['B', `今年は${quit}人退職したので、${plan}人の採用を予定しています。`]);
    L.push(['A', '残業が多いのは、どこですか。'], ['B', `${dept}です。`], ['A', `では、${dept}の人の配置を見直しましょう。来月までに案をください。`]);
    const qa = [['残業の合計は?', `${ot}時間`], ['1人あたり、平均何時間?', `${ot / staff}時間`, 9]];
    if (lv >= 2) qa.push(['有給の取得率は、目標まで何ポイント?', `${70 - now}ポイント`]);
    if (lv >= 3) qa.push(['採用の予定は何人?', `${plan}人`]);
    qa.push(['残業が多いのはどこで、何をする?', `${dept}の人の配置を見直す`]);
    return { topic: '会議 · 総務の報告', intro: '会議の聞き取りです。社長と総務課長が、残業や人のことを話しています。', points: '人数と時間、決まったこと', names: { A: '社長', B: '総務課長' }, lines: L, qa,
      summary: `社員${staff}人で残業は合計${ot}時間、1人平均${ot / staff}時間。${dept}の人の配置を見直し、来月までに案を出す。` };
  });

  // ---- 8. 電話:車両の修理見積もり ----
  DN.C.scenarios.push(lv => {
    const parts = pick([18, 24, 32]), labor = pick([6, 8, 12]), days = pick([5, 7, 10]), rent = pick([8000, 10000, 12000]);
    const L = [
      ['B', '整備工場の鈴木です。3号車のパッカー車の、修理の見積もりが出ました。'],
      ['A', 'お願いします。'],
      ['B', `部品代が${parts}万円、工賃が${labor}万円です。`],
    ];
    if (lv >= 2) L.push(['B', `部品の取り寄せがあるので、修理には${days}日かかります。`]);
    if (lv >= 3) L.push(['B', `その間、代車を1日${comma(rent)}円でお貸しできます。`]);
    L.push(['A', 'わかりました。社内で確認して、折り返します。']);
    const qa = [['修理するのは、何号車?', '3号車のパッカー車'], ['修理代の合計は?', `${parts + labor}万円`, 7]];
    if (lv >= 2) qa.push(['修理に何日かかる?', `${days}日`]);
    if (lv >= 3) qa.push(['修理の間ずっと代車を借りると、代車代はいくら?', yen(rent * days), 9]);
    if (lv >= 4) qa.push(['修理代と代車代を合わせると?', yen((parts + labor) * 1e4 + rent * days), 12]);
    return { topic: '電話 · 修理の見積もり', intro: '電話の聞き取りです。整備工場から、車両の修理の見積もりです。', points: '金額と日数', names: { A: '自社', B: '整備工場' }, lines: L, qa,
      summary: `3号車の修理は部品${parts}万円と工賃${labor}万円で、合計${parts + labor}万円。${lv >= 2 ? `修理に${days}日かかる。` : ''}社内で確認して折り返す。` };
  });
})();
