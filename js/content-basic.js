// 暗算の基礎(basic)と、数字で考える(think)
(() => {
  const { pick, rint, comma, man, yen, dec } = DN.U;

  // ---------- 暗算の基礎:レベル=習得する技 ----------
  const B = {
    1: [ // 2桁の足し算(繰り上がり)
      () => {
        let a, b;
        do { a = rint(16, 79); b = rint(12, 69); } while (a % 10 === 0 || (a % 10) + (b % 10) < 10 || b % 10 === 0);
        const need = 10 - (a % 10);
        return { topic: '足し算', focus: '足し算です。', body: [`${a} + ${b}`], ask: 'いくつ?', a: `${a + b}`, thinkMul: 0.7,
          e: `${a}は、あと${need}で${a + need}。${b}から${need}を渡して${b - need}。${a + need} + ${b - need}で${a + b}。キリのいい数を作るのがコツ。`,
          steps: [{ ask: `${a}をキリのいい数にするには、いくつ足す?`, a: `${need}。${a + need}になります` }, { ask: `では、${a + need} + ${b - need}は?`, a: `${a + b}` }] };
      },
    ],
    2: [ // 引き算とおつり
      () => {
        let a, b;
        do { a = rint(52, 98); b = rint(13, 49); } while (a % 10 >= b % 10 || b % 10 === 0);
        const r = Math.ceil(b / 10) * 10, extra = r - b;
        return { topic: '引き算', focus: '引き算です。', body: [`${a} − ${b}`], ask: 'いくつ?', a: `${a - b}`, thinkMul: 0.8,
          e: `${b}を${r}とみなして、${a} − ${r}で${a - r}。引きすぎた${extra}を戻して${a - b}。`,
          steps: [{ ask: `まず、${a} − ${r}は?`, a: `${a - r}` }, { ask: `引きすぎた${extra}を戻すと?`, a: `${a - b}` }] };
      },
      () => {
        let p; do { p = rint(112, 988); } while (p % 10 === 0);
        const h = Math.floor(p / 100), t = Math.floor(p / 10) % 10, o = p % 10;
        return { topic: 'おつり', focus: 'おつりの計算です。', body: [`1,000円で、${p}円の買い物`], ask: 'おつりはいくら?', a: `${1000 - p}円`, thinkMul: 0.8,
          e: `百の位と十の位は9から、一の位だけ10から引きます。9−${h}で${9 - h}、9−${t}で${9 - t}、10−${o}で${10 - o}。つなげて${1000 - p}円。` };
      },
    ],
    3: [ // 2桁×1桁
      () => {
        let a; do { a = rint(13, 48); } while (a % 10 === 0);
        const m = rint(3, 9), tens = a - (a % 10), ones = a % 10;
        return { topic: '掛け算', focus: '掛け算です。', body: [`${a} × ${m}`], ask: 'いくつ?', a: `${a * m}`,
          e: `${a}を${tens}と${ones}に分けます。${tens}×${m}で${tens * m}、${ones}×${m}で${ones * m}。足して${a * m}。`,
          steps: [{ ask: `${tens} × ${m}は?`, a: `${tens * m}` }, { ask: `${ones} × ${m}は?`, a: `${ones * m}` }, { ask: `${tens * m} + ${ones * m}は?`, a: `${a * m}` }] };
      },
      () => {
        const a = rint(14, 98);
        return { topic: '×5', focus: '5を掛けます。', body: [`${a} × 5`], ask: 'いくつ?', a: `${a * 5}`, thinkMul: 0.8,
          e: `×5は、×10して半分。${a}×10で${a * 10}、その半分で${a * 5}。`,
          steps: [{ ask: `${a} × 10は?`, a: `${a * 10}` }, { ask: 'その半分は?', a: `${a * 5}` }] };
      },
    ],
    4: [ // ゼロと万・億の扱い
      () => {
        const x = pick([25, 30, 35, 40, 45, 60, 80, 120, 250]);
        return { topic: '月額×12', focus: '1年分を計算します。', body: [`月${x}万円`, '12か月分'], ask: 'いくら?', a: man(x * 12),
          e: `12は10と2に分けます。${x}×10で${x * 10}、${x}×2で${x * 2}。足して${x * 12}万円。` };
      },
      () => {
        const a = rint(2, 9), b = rint(2, 9);
        return { topic: 'ゼロの計算', focus: 'ゼロのつく掛け算です。', body: [`${a}0 × ${b}00`], ask: 'いくつ?', a: comma(a * b * 1000),
          e: `ゼロを外して${a}×${b}で${a * b}。外したゼロは合わせて3つ。${a * b}にゼロ3つで${comma(a * b * 1000)}。` };
      },
      () => {
        const a = pick([2000, 3000, 4000, 5000, 6000, 8000]), b = pick([2, 3, 4, 5]);
        return { topic: '万と億', focus: '億の位が出てきます。', body: [`${man(a)} × ${b}`], ask: 'いくら?', a: man(a * b),
          e: `1万が1万個で1億。${comma(a)}万×${b}で${comma(a * b)}万。1万万は1億なので、${man(a * b)}。` };
      },
    ],
    5: [ // パーセントの基本
      () => {
        const base = pick([1200, 2400, 3600, 4800, 6000, 8400]), p = pick([10, 5, 20, 30, 15, 1]);
        const ten = base / 10, ans = Math.round(base * p / 100);
        const tips = {
          10: `10%は、1桁ずらすだけ。${man(base)}の10%は${man(ten)}。`,
          5: `5%は、10%の半分。10%が${man(ten)}、その半分で${man(ans)}。`,
          20: `20%は、10%の2倍。${man(ten)}×2で${man(ans)}。`,
          30: `30%は、10%の3倍。${man(ten)}×3で${man(ans)}。`,
          15: `15%は、10%と5%の合計。${man(ten)}と${man(ten / 2)}を足して${man(ans)}。`,
          1: `1%は、2桁ずらすだけ。${man(base)}の1%は${man(ans)}。`,
        };
        const it = { topic: 'パーセント', focus: `${p}%を出します。`, body: [`${man(base)}の${p}%`], ask: 'いくら?', a: man(ans), e: tips[p] };
        if (p === 15) it.steps = [{ ask: 'まず10%は?', a: man(ten) }, { ask: '5%は?', a: man(ten / 2) }, { ask: '足すと?', a: man(ans) }];
        if (p === 20 || p === 30) it.steps = [{ ask: 'まず10%は?', a: man(ten) }, { ask: `それを${p / 10}倍すると?`, a: man(ans) }];
        return it;
      },
    ],
    6: [ // 割合と分数
      () => {
        const [whole, pct] = pick([[40, 25], [40, 75], [50, 30], [50, 60], [60, 25], [80, 25], [80, 40], [120, 25], [200, 15], [200, 35]]);
        const part = whole * pct / 100;
        return { topic: '何%?', focus: '割合を出します。', body: [`${whole}件のうち、${part}件`], ask: '何%?', a: `${pct}%`,
          e: `全体を100にそろえます。${whole}件を100とみなすと、${part}件は${pct}。なので${pct}%。` };
      },
      () => {
        const [q, pct, why] = pick([
          ['2分の1', '50%', '半分なので50%。'], ['4分の1', '25%', '100を4で割って25%。'], ['4分の3', '75%', '4分の1が25%、その3つ分で75%。'],
          ['5分の1', '20%', '100を5で割って20%。'], ['8分の1', '12.5%', '4分の1の25%の、さらに半分で12.5%。'], ['8分の3', '37.5%', '8分の1が12.5%、その3つ分で37.5%。'],
        ]);
        return { topic: '分数とパーセント', focus: '分数をパーセントにします。', body: [q], ask: '何%?', a: pct, e: why, thinkMul: 0.7 };
      },
      () => {
        const n = pick([300, 450, 700, 1200, 1800]);
        return { topic: '÷25', focus: '25で割ります。', body: [`${comma(n)} ÷ 25`], ask: 'いくつ?', a: `${n * 4 / 100}`,
          e: `÷25は、×4して÷100。${comma(n)}×4で${comma(n * 4)}、÷100で${n * 4 / 100}。`,
          steps: [{ ask: `${comma(n)} × 4は?`, a: comma(n * 4) }, { ask: 'それを100で割ると?', a: `${n * 4 / 100}` }] };
      },
    ],
    7: [ // 2桁×2桁
      () => {
        const a = rint(12, 38), r = rint(2, 9), b = 10 + r;
        return { topic: '2桁の掛け算', focus: '2桁どうしの掛け算です。', body: [`${a} × ${b}`], ask: 'いくつ?', a: comma(a * b),
          e: `${b}を10と${r}に分けます。${a}×10で${a * 10}、${a}×${r}で${a * r}。足して${a * b}。`,
          steps: [{ ask: `${a} × 10は?`, a: `${a * 10}` }, { ask: `${a} × ${r}は?`, a: `${a * r}` }, { ask: '足すと?', a: `${a * b}` }] };
      },
      () => {
        const a = pick([12, 16, 24, 28, 32, 36, 44, 48]);
        return { topic: '×25', focus: '25を掛けます。', body: [`${a} × 25`], ask: 'いくつ?', a: comma(a * 25),
          e: `×25は、4で割って×100。${a}÷4で${a / 4}、×100で${comma(a * 25)}。` };
      },
      () => {
        const a = rint(12, 48);
        return { topic: '×99', focus: '99を掛けます。', body: [`${a} × 99`], ask: 'いくつ?', a: comma(a * 99),
          e: `99は100より1少ない。${a}×100で${a * 100}、そこから${a}を引いて${comma(a * 99)}。` };
      },
    ],
    8: [ // ざっくり見積もり
      () => {
        const [p, pr] = pick([[198, 200], [298, 300], [498, 500], [980, 1000], [1980, 2000], [2980, 3000]]);
        const [n, nr] = pick([[29, 30], [31, 30], [48, 50], [52, 50], [99, 100], [101, 100], [198, 200], [205, 200]]);
        return { topic: 'ざっくり計算', focus: 'だいたいの金額を出します。', body: [`${comma(p)}円の品を${n}個`], ask: '約いくら?', a: `約${yen(pr * nr)}`,
          e: `${comma(p)}円を${comma(pr)}円、${n}個を${nr}個とみなします。${comma(pr)}×${nr}で約${yen(pr * nr)}。正確には${yen(p * n)}。桁が合っていれば合格です。` };
      },
    ],
  };
  DN.C.basicMax = 8;
  DN.C.basic = lv => {
    const tier = Math.random() < 0.6 ? lv : rint(Math.max(1, lv - 2), lv);
    const it = pick(B[tier])();
    // 新しく習う技のときだけ、半分の確率で「手順つき」にする
    if (it.steps && !(tier === lv && Math.random() < 0.5)) delete it.steps;
    return Object.assign(it, { cat: 'basic', tier });
  };

  // ---------- 数字で考える:直感の落とし穴 ----------
  const T = [
    [1, () => {
      const n = pick([1000, 2000, 5000, 10000, 30000]), inc = n * 1.1;
      return { topic: '税抜きの逆算', focus: '税抜きの金額を出します。', body: [`税込み${comma(inc)}円`], ask: '税抜き、消費税10%では、いくら?', a: `${comma(n)}円`,
        e: `税込みは、税抜きの1.1倍。なので1.1で割って${comma(n)}円。税込みから10%を引いた${comma(inc * 0.9)}円は間違いです。` };
    }],
    [1, () => {
      const a = pick([20, 25, 40]), b = a + 5, pct = dec(5 / a * 100, 1);
      return { topic: 'ポイントと%', focus: '2つの言い方を区別します。', body: [`粗利率が${a}%から${b}%に上がった`], ask: '何ポイント上がった? 率では何%上がった?', a: `5ポイント。率では${pct}%の上昇`,
        e: `差の5は「5ポイント」。元の${a}に対して5増えたので、率では${pct}%。会議でよく混ざる2つです。` };
    }],
    [2, () => {
      const p = pick([10, 20, 30, 50]), r = (100 + p) * (100 - p) / 100;
      return { topic: '上げて下げる', focus: '元に戻るか考えます。', body: [`単価を${p}%上げて、翌月${p}%下げた`], ask: '元の何%になった?', a: `${r}%`,
        e: `100が${100 + p}になり、そこから${100 + p}の${p}%、つまり${(100 + p) * p / 100}を引くので${r}。同じ%の上げ下げでも元には戻りません。` };
    }],
    [2, () => {
      const a = pick([20, 30, 40, 50, 60]), b = pick([10, 20, 30, 50]);
      return { topic: '割合の割合', focus: '全体に対する割合を出します。', body: [`回収量の${a}%が廃プラスチック`, `そのうち${b}%をリサイクル`], ask: 'リサイクル分は、回収量全体の何%?', a: `${a * b / 100}%`,
        e: `${a}%の、さらに${b}%。${a}×${b}÷100で${a * b / 100}%。${a + b}%や${b}%と答えがちな問題です。` };
    }],
    [3, () => {
      const [p, h, q] = pick([[3, 6, 2], [4, 6, 3], [2, 9, 3], [5, 4, 2], [6, 4, 8]]);
      return { topic: '人数と時間', focus: '作業時間を出します。', body: [`${p}人で${h}時間かかる作業`], ask: `${q}人なら何時間?`, a: `${p * h / q}時間`,
        e: `まず作業の総量。${p}人×${h}時間で${p * h}人時。それを${q}人で割って${p * h / q}時間。`,
        steps: [{ ask: '全部で何人時の作業?', a: `${p * h}人時` }, { ask: `${q}人で割ると?`, a: `${p * h / q}時間` }] };
    }],
    [3, () => {
      const [v1, v2, d] = pick([[60, 40, 120], [30, 60, 60], [40, 60, 120], [20, 30, 60]]);
      const t = d / v1 + d / v2, avg = 2 * d / t;
      return { topic: '平均の落とし穴', focus: '平均の速さを出します。', body: [`収集車が同じ道を往復`, `行きは時速${v1}キロ、帰りは時速${v2}キロ`], ask: '往復の平均は時速何キロ?', a: `時速${avg}キロ`,
        e: `単純平均の${(v1 + v2) / 2}キロではありません。片道${d}キロなら、行き${d / v1}時間、帰り${d / v2}時間。${2 * d}キロを${t}時間で走るので時速${avg}キロ。` };
    }],
    [3, () => {
      const [a, b] = pick([[10, 10], [20, 10], [20, 20], [30, 10]]), left = (100 - a) * (100 - b) / 100;
      return { topic: '割引の重ねがけ', focus: '合計の割引率を出します。', body: [`${a}%引きのあと、さらに${b}%引き`], ask: '合計で何%引き?', a: `${100 - left}%引き`,
        e: `2回目は、下がった値段からの${b}%。100が${100 - a}、その${b}%を引いて${left}。なので${a + b}%ではなく${100 - left}%引き。` };
    }],
    [4, () => {
      const [cost, save] = pick([[600, 10], [600, 25], [900, 15], [1200, 20], [1200, 50], [1800, 25], [2400, 50]]);
      const m = cost / save;
      return { topic: '投資の回収', focus: '元が取れる年数を出します。', body: [`${man(cost)}の設備を入れると`, `月${man(save)}のコストが下がる`], ask: '何年で元が取れる?', a: `${m}か月、つまり${dec(m / 12, 1)}年`,
        e: `${comma(cost)}÷${save}で${m}か月。12で割って${dec(m / 12, 1)}年。`,
        steps: [{ ask: '何か月で元が取れる?', a: `${m}か月` }, { ask: 'それは何年?', a: `${dec(m / 12, 1)}年` }] };
    }],
    [4, () => {
      const d = pick([0.2, 0.3, 0.5]), v = pick([10, 20, 30]);
      return { topic: '体積と重さ', focus: '重さを出します。', body: [`比重${d}の廃棄物が${v}{m³|りゅうべ}`], ask: '何トン?', a: `${dec(v * d, 1)}トン`,
        e: `{m³|りゅうべ}×比重でトンになります。${v}×${d}で${dec(v * d, 1)}トン。` };
    }],
    [4, () => {
      const m = pick([8, 9, 12, 15]), n = pick([60, 72, 84]), diff = pick([-120, -60, 60, 90]), buy = m * n + diff;
      return { topic: 'リースか購入か', focus: '総額を比べます。', body: [`車両のリースは月${m}万円を${n}か月`, `購入なら${man(buy)}`], ask: 'どちらが、いくら安い?', a: `${diff > 0 ? 'リース' : '購入'}が${man(Math.abs(diff))}安い`,
        e: `リースの総額は${m}×${n}で${man(m * n)}。購入との差は${man(Math.abs(diff))}。実際は、整備や保険がリースに含まれるかでも判断が変わります。` };
    }],
    [5, () => {
      const [x, y] = pick([[30, 10], [20, 20], [10, 30], [60, 20]]), sales = x * 1 + y * 3, avg = dec(sales / (x + y), 2);
      return { topic: '加重平均', focus: '平均単価を出します。', body: [`A品目は1トン1万円で、月${x}トン`, `B品目は1トン3万円で、月${y}トン`], ask: '1トンあたりの平均単価は?', a: `${avg}万円`,
        e: `単価の平均の2万円ではなく、量で重みをつけます。売上は${x}万+${y * 3}万で${sales}万円。${x + y}トンで割って${avg}万円。` };
    }],
    [5, () => {
      const F = pick([300, 600]), v = pick([5, 8]), q = pick([500, 1000, 1500]), fixed = F * 1e4 / q;
      return { topic: '量とコスト', focus: '1トンあたりのコストを出します。', body: [`月の固定費${man(F)}`, `1トンあたりの変動費${comma(v * 1000)}円`, `月${comma(q)}トン処理`], ask: '1トンあたりのコストは?', a: `${comma(fixed + v * 1000)}円`,
        e: `固定費を量で割ると${man(F)}÷${comma(q)}トンで${comma(fixed)}円。変動費の${comma(v * 1000)}円を足して${comma(fixed + v * 1000)}円。量が増えるほど1トンあたりは下がります。` };
    }],
  ];
  DN.C.thinkMax = 5;
  DN.C.think = lv => {
    const pool = T.filter(([min]) => min <= lv);
    const fresh = pool.filter(([min]) => min === lv);
    const g = (fresh.length && Math.random() < 0.5 ? pick(fresh) : pick(pool))[1];
    const it = g();
    if (it.steps && lv > 3) delete it.steps;
    return Object.assign(it, { cat: 'think', thinkMul: it.thinkMul || 1.3 });
  };
})();
